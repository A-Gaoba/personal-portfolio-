import type React from "react"
import type { Metadata } from "next"
import { notFound } from "next/navigation"
import { Readex_Pro, Martian_Mono } from "next/font/google"
import { Analytics } from "@vercel/analytics/next"
import "../globals.css"
import { ThemeProvider } from "@/components/theme-provider"
import { I18nProvider } from "@/components/i18n/I18nProvider"
import JsonLd from "../components/JsonLd"
import Navbar from "../components/Navbar"
import Footer from "../components/Footer"
import { SITE_URL, absoluteUrl, ogImage } from "@/lib/site"
import { profile, verifiedSameAs } from "@/content/profile"
import { isLocale, localeDir, localeMeta, locales, localizePath, otherLocales } from "@/lib/i18n/config"
import { getDictionary } from "@/lib/i18n/dictionaries"
import { languageAlternates } from "@/lib/i18n/metadata"

// GAOBA identity fonts (same as the video skill): Readex Pro for text (Latin + Arabic), Martian Mono for labels/code.
const readex = Readex_Pro({
  subsets: ["latin", "arabic"],
  weight: ["300", "400", "500", "600", "700"],
  variable: "--font-sans",
  display: "swap",
})

const martianMono = Martian_Mono({
  subsets: ["latin"],
  weight: ["400", "500", "600"],
  variable: "--font-mono",
  display: "swap",
})

type LayoutProps = { children: React.ReactNode; params: Promise<{ locale: string }> }

/** Both languages are generated at build time; any other first segment is a 404. */
export function generateStaticParams() {
  return locales.map((locale) => ({ locale }))
}
export const dynamicParams = false

// Phase 0b (2026-11-07): one domain (SITE_URL), no placeholder verification codes, Open Graph image generated by
// public/og/{locale}.png (one per language). 2026-11-07 (i18n): per-language title/description/keywords and hreflang alternates.
export async function generateMetadata({ params }: LayoutProps): Promise<Metadata> {
  const { locale } = await params
  if (!isLocale(locale)) return {}
  const t = getDictionary(locale)
  return {
    metadataBase: new URL(SITE_URL),
    title: { default: t.meta.defaultTitle, template: t.meta.titleTemplate },
    description: t.meta.description,
    icons: {
      icon: [
        { url: "/portfolio-icon.svg", type: "image/svg+xml" },
        { url: "/avatar-icon.png", type: "image/png", sizes: "32x32" },
      ],
      apple: "/apple-touch-icon.png",
      shortcut: "/portfolio-icon.svg",
    },
    keywords: t.meta.keywords,
    authors: [{ name: t.meta.siteName, url: SITE_URL }],
    creator: t.meta.siteName,
    publisher: t.meta.siteName,
    formatDetection: { email: false, address: false, telephone: false },
    alternates: { canonical: localizePath(locale, "/"), languages: languageAlternates("/") },
    openGraph: {
      title: t.meta.defaultTitle,
      description: t.meta.description,
      url: localizePath(locale, "/"),
      siteName: t.meta.siteName,
      locale: localeMeta[locale].ogLocale,
      alternateLocale: otherLocales(locale).map((l) => localeMeta[l].ogLocale),
      type: "website",
      images: [ogImage(locale, t.meta.ogAlt)],
    },
    twitter: {
      card: "summary_large_image",
      title: t.meta.defaultTitle,
      description: t.meta.description,
      images: [ogImage(locale, t.meta.ogAlt).url],
      creator: profile.links.xHandle,
      site: profile.links.xHandle,
    },
    robots: {
      index: true,
      follow: true,
      googleBot: { index: true, follow: true, "max-video-preview": -1, "max-image-preview": "large", "max-snippet": -1 },
    },
    category: "technology",
  }
}

export default async function LocaleLayout({ children, params }: LayoutProps) {
  const { locale } = await params
  if (!isLocale(locale)) notFound()
  const t = getDictionary(locale)

  // Only facts already shown on the site (Phase 0b), now in the page's language.
  const jsonLd = [
    {
      "@context": "https://schema.org",
      "@type": "Person",
      "@id": `${SITE_URL}/#person`,
      name: profile.name,
      alternateName: profile.alternateNames,
      url: absoluteUrl(localizePath(locale, "/")),
      image: absoluteUrl(profile.image),
      email: `mailto:${profile.email}`,
      jobTitle: t.meta.jobTitle,
      sameAs: verifiedSameAs,
      knowsAbout: [
        "JavaScript", "TypeScript", "HTML5", "CSS3", "React", "Next.js", "Tailwind CSS", "Redux", "Node.js",
        "Express.js", "MongoDB", "PostgreSQL", "REST", "Prisma", "Jest", "Cypress", "Responsive Design", "Scrum",
      ],
      alumniOf: [
        { "@type": "CollegeOrUniversity", name: "Ufa University of Science and Technology" },
        { "@type": "CollegeOrUniversity", name: "Saint Petersburg Mining University" },
        { "@type": "CollegeOrUniversity", name: "University of Sana'a" },
      ],
      knowsLanguage: ["Arabic", "English", "Russian"],
    },
    {
      "@context": "https://schema.org",
      "@type": "WebSite",
      "@id": `${SITE_URL}/#website`,
      name: t.meta.siteName,
      url: absoluteUrl(localizePath(locale, "/")),
      description: t.meta.description,
      author: { "@id": `${SITE_URL}/#person` },
      publisher: { "@id": `${SITE_URL}/#person` },
      inLanguage: locales,
    },
  ]

  return (
    <html
      lang={locale}
      dir={localeDir(locale)}
      suppressHydrationWarning
      className={`${readex.variable} ${martianMono.variable}`}
    >
      <body className="font-sans antialiased">
        {/* GAOBA decision (2026-11-07): light by default for every visitor; dark only when chosen with the toggle. */}
        <ThemeProvider attribute="class" defaultTheme="light" enableSystem={false} disableTransitionOnChange>
          <I18nProvider locale={locale} messages={t}>
            <Navbar />
            {children}
            <Footer locale={locale} t={t} />
          </I18nProvider>
        </ThemeProvider>
        <JsonLd data={jsonLd} />
        <Analytics />
      </body>
    </html>
  )
}
