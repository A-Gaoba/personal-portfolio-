/**
 * Central site settings (Phase 0b, 2026-11-07).
 *
 * SITE_URL is the ONE place the public domain is defined. Every canonical URL, Open Graph URL, sitemap entry,
 * robots.txt line and JSON-LD id is built from it. To move to a custom domain later, set NEXT_PUBLIC_SITE_URL in
 * Vercel (no code change) and add a permanent redirect from gaoba.vercel.app.
 */
export const SITE_URL = (process.env.NEXT_PUBLIC_SITE_URL ?? "https://gaoba.vercel.app").replace(/\/+$/, "")

export const SITE_NAME = "Abdulrahman Gaoba"

/** Absolute URL for a site path ("/about" -> "https://gaoba.vercel.app/about"). */
export const absoluteUrl = (path = "/") => `${SITE_URL}${path.startsWith("/") ? path : `/${path}`}`

/**
 * Unverified claims switch (Phase 0a).
 *
 * Numbers and achievement metrics that have no source in the repository (users, revenue, growth %, ratings,
 * "50+ projects", "5+ years", skill percentages, service prices…) are HIDDEN, not deleted: the data stays in the
 * components so each value can be restored once GAOBA confirms it (docs/portfolio-audit/10-open-questions.md).
 * Keep this false until every value shown has been confirmed.
 */
export const SHOW_UNVERIFIED_CLAIMS = false

/**
 * Open Graph image per language (1200×630 PNGs in public/og/, generated by scripts/generate-og-images.mjs with real
 * Chrome so Arabic is shaped correctly). Pages that define their own `openGraph` reference this explicitly.
 */
export const ogImage = (locale: "en" | "ar", alt: string) => ({
  url: `/og/${locale}.png`,
  width: 1200,
  height: 630,
  alt,
  type: "image/png",
})
